-- Veritek CRM schema for PostgreSQL (converted from the original SQLite schema).
-- Dates and times are ISO-8601 text, money is integer minor units, flags are 0/1 integers.
CREATE EXTENSION IF NOT EXISTS citext;

-- Veritek CRM — Customer & Order Control System: initial schema.
-- Conventions: instants are ISO-8601 UTC text; business dates are 'YYYY-MM-DD' text; money is BIGINT
-- minor units with an explicit ISO currency; quantities are DOUBLE PRECISION rounded to 3 decimals in the service layer.
-- History tables are append-only: no API deletes from them.

CREATE TABLE settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at TEXT,
  updated_by BIGINT
);

CREATE TABLE counters (key TEXT PRIMARY KEY, value BIGINT NOT NULL);

