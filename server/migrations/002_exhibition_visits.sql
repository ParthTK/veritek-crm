-- Customers met at an exhibition. One row per customer per exhibition; an enquiry raised from the visit is
-- linked here, so "customers visited" and "enquiries generated" can be compared.
CREATE TABLE exhibition_visits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id BIGINT NOT NULL REFERENCES campaigns(id),
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  contact_id BIGINT REFERENCES contacts(id),
  visited_on TEXT NOT NULL,
  met_by BIGINT REFERENCES users(id),
  interest TEXT,
  notes TEXT,
  outcome TEXT NOT NULL DEFAULT 'follow_up',
  enquiry_id BIGINT REFERENCES enquiries(id),
  created_by BIGINT REFERENCES users(id),
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (campaign_id, customer_id)
);
CREATE INDEX ix_exhibition_visits_customer ON exhibition_visits(customer_id);
CREATE INDEX ix_exhibition_visits_enquiry ON exhibition_visits(enquiry_id);
